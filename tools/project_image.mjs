import {mkdir,writeFile,readFile,readdir,unlink} from 'node:fs/promises';
import {baseProject,storageProject,capabilities} from '../examples/s3_style_lab/project/demo.mjs';
import {encodeProject,decodeProject} from '../packages/project-codec/index.js';
import {compileCatalog,inspectCatalog} from '../packages/project-codec/catalog.js';
import {prepareProvisioningProject,prepareStockProject,provisioningCapabilities} from '../examples/s3_style_lab/project/provision.mjs';
const output=new URL('../local/project-image/',import.meta.url),fs=new URL('files/',output);await mkdir(fs,{recursive:true});
const fullJson=process.argv.indexOf('--project-json');
if(fullJson>=0&&process.argv.includes('--preserve'))throw Error('Choose --project-json or --preserve');
// These system services are registered by the example application.
const compileCapabilities=provisioningCapabilities(capabilities);
// Explicit authoring files retain their own entry page and composition.
const project=fullJson>=0
 ? prepareProvisioningProject(JSON.parse(await readFile(process.argv[fullJson+1],'utf8')))
 : prepareStockProject(storageProject);
// A previous owner project may be explicitly included during provisioning. It is
// never implicitly read from browser storage or fetched while building firmware.
const preserve=process.argv.indexOf('--preserve');
if(preserve>=0){
 const old=decodeProject(new Uint8Array(await readFile(process.argv[preserve+1])),compileCapabilities);
 for(const [name,style] of Object.entries(old.styles)){if(project.styles[name])throw Error('Preserved style collision '+name);project.styles[name]=style;}
 for(const [name,screen] of Object.entries(old.screens)){const id='workbench-'+name;if(id.length>63||project.screens[id])throw Error('Preserved screen collision');project.screens[id]={...screen,id,name:'Мастерская · '+screen.name};}
 await writeFile(new URL('previous-project.cbor',output),encodeProject(old,compileCapabilities));
}
const base=encodeProject(baseProject,compileCapabilities),whole=encodeProject(project,compileCapabilities);
const {files,index}=compileCatalog(baseProject,project,compileCapabilities);inspectCatalog(files.get('catalog.0'),files);
// Validate everything before replacing generated files. This is build output,
// never the live MCU filesystem or the explicitly supplied authoring document.
for(const file of await readdir(fs))if(/^(?:[01][st]\d{3}\.cbor|catalog\.[01])$/.test(file))await unlink(new URL(file,fs));
for(const [file,bytes] of files)await writeFile(new URL(file,fs),bytes);
for(const [name,document] of [['base',baseProject],['project',project]]){
 await writeFile(new URL(name+'.json',output),JSON.stringify(document,null,2)+'\n');await writeFile(new URL(name+'.cbor',output),encodeProject(document,compileCapabilities));
}
await writeFile(new URL('catalog.json',output),JSON.stringify(index,(_,value)=>value instanceof Map?Object.fromEntries(value):value instanceof Uint8Array?{cborBytes:value.length}:value,2)+'\n');
await writeFile(new URL('../examples/s3_style_lab/main/project.generated.hpp',import.meta.url),'// Generated by tools/project_image.mjs; ROM base.\n#pragma once\n#include <cstdint>\ninline constexpr uint8_t initial_project_packet[]{'+[...base].join(',')+'};\n');
console.log(JSON.stringify({baseBytes:base.length,projectBytes:whole.length,files:[...files].map(([name,bytes])=>({name,bytes:bytes.length})),base:index.base}));
