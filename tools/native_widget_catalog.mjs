import {readFileSync,writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
const dir=new URL('../examples/s3_style_lab/main/native_widgets/',import.meta.url);
export const nativeWidgets=JSON.parse(readFileSync(new URL('catalog.json',dir),'utf8'));
const output='// Generated by tools/native_widget_catalog.mjs from catalog.json.\n'+
  'bool lab_widgets::register_examples(lvgl_cbor::WidgetRegistry &registry) {\n  return '+nativeWidgets.map(w=>
  `registry.add({${w.id}, ${JSON.stringify(w.name)}, ${JSON.stringify(w.abi)}, ${w.symbol}::create, ${w.symbol}::execute, R"catalog(${JSON.stringify(w.contract)})catalog"${w.activate?`, {}, ${w.symbol}::${w.activate}`:''}})`).join(' &&\n    ')+';\n}\n';
const path=new URL('catalog.generated.hpp',dir);
if(process.argv[1]&&fileURLToPath(import.meta.url)===process.argv[1]){
 if(process.argv.includes('--check')){if(readFileSync(path,'utf8')!==output)throw Error('Native widget metadata is stale');}
 else writeFileSync(path,output);
}
