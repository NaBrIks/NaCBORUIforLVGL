"""Rebuild small owned gallery assets and embed them. Requires Pillow 12.2.0."""
from pathlib import Path
import hashlib, json, math, struct
from PIL import Image, ImageDraw
root=Path(__file__).resolve().parents[1]
assets=root/'assets/graphics'; assets.mkdir(parents=True,exist_ok=True)
w,h=96,64
image=Image.new('RGBA',(w,h))
p=image.load()
for y in range(h):
    for x in range(w):
        alpha=round(255*min(1,max(0,(x-4)/28)))
        p[x,y]=(round(255*x/(w-1)),round(255*y/(h-1)),190,alpha)
draw=ImageDraw.Draw(image)
draw.rounded_rectangle((14,12,81,51),radius=12,outline=(255,255,255,255),width=3)
draw.ellipse((37,21,59,43),fill=(35,180,120,220))
image.save(assets/'sample.png')
image.convert('RGB').save(assets/'sample.jpg',quality=90,progressive=False,subsampling=0)
image.convert('RGB').save(assets/'sample.bmp')
frames=[]
for i in range(8):
    f=Image.new('RGB',(w,h),(20,30,45)); d=ImageDraw.Draw(f)
    d.rectangle((8,27,87,38),outline=(90,120,145),width=2)
    d.rectangle((10,29,10+9*i,36),fill=(40,195,140))
    d.ellipse((6+10*i,6,20+10*i,20),fill=(245,170,35))
    frames.append(f)
frames[0].save(assets/'sample.gif',save_all=True,append_images=frames[1:],duration=120,loop=0,disposal=2,optimize=False)
rgb=image.convert('RGB')
blobs={
 'rgb565': b''.join(struct.pack('<H',((r>>3)<<11)|((g>>2)<<5)|(b>>3)) for r,g,b in rgb.get_flattened_data()),
 'rgb888': b''.join(bytes((b,g,r)) for r,g,b in rgb.get_flattened_data()),
 'xrgb8888': b''.join(bytes((b,g,r,255)) for r,g,b in rgb.get_flattened_data()),
 'argb8888': b''.join(bytes((b,g,r,a)) for r,g,b,a in image.get_flattened_data()),
 'a8': bytes(round(255*max(0,1-math.hypot((x-w/2)/(w/2),(y-h/2)/(h/2)))) for y in range(h) for x in range(w)),
}
# A shared 176x108 opaque backdrop makes transparency comparable in every sample.
checker=Image.new('RGB',(176,108))
checker.putdata([(196,196,196) if ((x//8+y//8)&1) else (236,236,236) for y in range(108) for x in range(176)])
checker.save(assets/'checker.png')
blobs['checker']=b''.join(struct.pack('<H',((r>>3)<<11)|((g>>2)<<5)|(b>>3)) for r,g,b in checker.get_flattened_data())
# Owned multi-path SVG: all geometry remains SVG, never rasterized by this tool.
paths=['<svg xmlns="http://www.w3.org/2000/svg" width="160" height="96" viewBox="0 0 160 96">',
       '<path d="M8 8H152V88H8Z" fill="#1c385c" fill-opacity="0.82"/>',
       '<path d="M8 58Q46 17 86 55T152 38V88H8Z" fill="#328b6c"/>',
       '<path d="M8 73C38 51 64 76 92 58S135 56 152 62V88H8Z" fill="#65b574"/>',
       '<path d="M111 24C111 10 133 10 133 24S111 38 111 24Z" fill="#ffd06a"/>',
       '<path d="M22 79Q64 34 110 88H86Q61 51 38 84Z" fill="#95d4ed" fill-opacity="0.9"/>']
for i in range(8):
    x=18+i*16; y=46+(i%3)*6
    paths.append(f'<path d="M{x} {y+15}L{x+6} {y}L{x+12} {y+15}H{x+8}V{y+23}H{x+4}V{y+15}Z" fill="{["#174c37","#28604b","#123e36"][i%3]}"/>')
for i in range(5):
    x=22+i*21; y=18+(i%2)*4
    paths.append(f'<path d="M{x} {y}Q{x+4} {y-5} {x+8} {y}Q{x+12} {y-5} {x+16} {y}" fill="none" stroke="#e9f6f1" stroke-width="1.6"/>')
paths+=['<path d="M131 74L139 63L147 74Z" fill="#e68654"/>',
        '<path d="M133 74H145V86H133Z" fill="#f4d2a8"/>',
        '<path d="M137 79H141V86H137Z" fill="#6d3941"/>','</svg>']
blobs['landscape_svg']='\n'.join(paths).encode('utf-8')
(assets/'landscape.svg').write_bytes(blobs['landscape_svg'])
# LVGL v9 image header, same layout as LVGLImage.py ImageHeader.binary.
blobs['bin']=struct.pack('<BBHHHHH',0x19,0x12,0,w,h,w*2,0)+blobs['rgb565']
(assets/'sample.bin').write_bytes(blobs['bin'])
palette=b''.join(bytes((round(255*i/15),round(255*(15-i)/15),70,255)) for i in range(16))
blobs['i4']=palette+bytes((min(15,(2*x)*16//w)<<4)|min(15,(2*x+1)*16//w) for y in range(h) for x in range(w//2))
for name,file in [('png','sample.png'),('jpeg','sample.jpg'),('bmp','sample.bmp'),('gif','sample.gif')]: blobs[name]=(assets/file).read_bytes()
for icon in ['heart','cloud']:
    svg=(assets/'tabler'/f'{icon}.svg').read_text(encoding='utf-8')
    svg=svg[svg.index('<svg'):].replace('width="24"','width="96"').replace('height="24"','height="96"').replace('currentColor','#20a8a0')
    blobs['tabler_'+icon]=svg.encode('utf-8')
lines=['// Generated by examples/windows_player/tools/generate_graphics_assets.py.','// Owned procedural assets: MIT. Tabler SVG: retained MIT notice under assets/graphics/tabler.','#pragma once','#include <cstdint>','namespace gallery_assets {','inline constexpr unsigned width=96,height=64;']
for name,data in blobs.items():
    lines.append('inline constexpr uint8_t '+name+'[]={')
    for at in range(0,len(data),24): lines.append(','.join(str(v) for v in data[at:at+24])+',')
    lines.append('};')
catalog=json.loads((root/'graphics-sample.json').read_text(encoding='utf-8-sig'))
lines.append('inline constexpr const char *catalog=R\"catalog('+json.dumps(catalog,separators=(',',':'),ensure_ascii=False)+')catalog\";')
lines.append('}')
(root/'src/graphics_assets.generated.hpp').write_text('\n'.join(lines)+'\n',encoding='utf-8')
(assets/'manifest.json').write_text(json.dumps({name:{'bytes':len(data),'sha256':hashlib.sha256(data).hexdigest()} for name,data in blobs.items()},indent=2)+'\n',encoding='utf-8')
print('Gallery assets:',len(blobs),'embedded sources;',sum(map(len,blobs.values())),'bytes')
